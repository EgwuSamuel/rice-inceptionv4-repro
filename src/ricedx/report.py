def _load_runs(folder):
    rows = [json.loads(p.read_text()) for p in sorted(Path(folder).glob("*.json"))]
    return pd.DataFrame(rows)


def _mean_sd(series, digits=4):
    s = pd.Series(series, dtype=float)
    if len(s) == 1 or s.std(ddof=1) != s.std(ddof=1):
        return f"{s.mean():.{digits}f}"
    return f"{s.mean():.{digits}f} ± {s.std(ddof=1):.{digits}f}"


def _md(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def _pooled_oof(out, model, n):
    """Out-of-fold logits for every primary image (each image tested once)."""
    logits = None
    for p in sorted((out / "runs" / "benchmark").glob(f"{model}_fold*.npz")):
        z = np.load(p)
        if logits is None:
            logits = np.full((n, z["logits"].shape[1]), np.nan)
        logits[z["test_idx"]] = z["logits"]
    return logits


def _plot_confusion(cm, names, title, path, normalise=True):
    m = cm.astype(float)
    if normalise:
        m = m / np.maximum(m.sum(1, keepdims=True), 1)
    fig, ax = plt.subplots(figsize=(4.6, 4.0))
    im = ax.imshow(m, cmap="Blues", vmin=0, vmax=1 if normalise else None)
    ax.set_xticks(range(len(names)), names, rotation=35, ha="right", fontsize=8)
    ax.set_yticks(range(len(names)), names, fontsize=8)
    for i in range(m.shape[0]):
        for j in range(m.shape[1]):
            txt = f"{m[i, j]:.2f}\n({cm[i, j]})" if normalise else str(cm[i, j])
            ax.text(j, i, txt, ha="center", va="center", fontsize=7,
                    color="white" if m[i, j] > 0.6 * np.nanmax(m) else "black")
    ax.set_xlabel("Predicted")
    ax.set_ylabel("True")
    ax.set_title(title, fontsize=9)
    fig.colorbar(im, ax=ax, fraction=0.046)
    fig.tight_layout()
    fig.savefig(path, dpi=300)
    plt.close(fig)


def _reliability(probs_raw, probs_cal, y, path, n_bins=15):
    fig, ax = plt.subplots(figsize=(4.2, 4.0))
    edges = np.linspace(0, 1, n_bins + 1)
    for probs, lab in ((probs_raw, "before TS"), (probs_cal, "after TS")):
        conf, corr = probs.max(1), probs.argmax(1) == y
        xs, ys = [], []
        for lo, hi in zip(edges[:-1], edges[1:]):
            b = (conf > lo) & (conf <= hi)
            if b.any():
                xs.append(conf[b].mean())
                ys.append(corr[b].mean())
        ax.plot(xs, ys, marker="o", ms=3, label=f"{lab} (ECE {E.expected_calibration_error(probs, y):.3f})")
    ax.plot([0, 1], [0, 1], "k--", lw=0.8)
    ax.set_xlabel("Confidence")
    ax.set_ylabel("Accuracy")
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(path, dpi=300)
    plt.close(fig)


def build_report(cfg, df, ext_df, out, log):
    out = Path(out)
    tables, figs = out / "tables", out / "figures"
    names = cfg["data"]["display_names"]
    n_cls = len(names)
    labels = list(range(n_cls))
    reps = cfg["experiments"].get("bootstrap_reps", 2000)
    md = ["# Results summary", "",
          "All numbers below are generated by `python -m ricedx.run_all`; do not edit by hand.", ""]

    # ---- Table 1: dataset ------------------------------------------------- #
    t1 = df.groupby("class_name").agg(images=("path", "size"), source_photographs=("group", "nunique"))
    t1 = t1.reindex(cfg["data"]["classes"]).reset_index()
    t1.to_csv(tables / "table1_dataset.csv", index=False)
    md += ["## Table 1. Primary dataset", "", _md(t1), ""]
    if ext_df is not None:
        t1e = ext_df.groupby("class_name").size().rename("images").reset_index()
        t1e.to_csv(tables / "table1b_external.csv", index=False)
        md += ["External set (shared classes):", "", _md(t1e), ""]

    # ---- Table 2: leakage audit ------------------------------------------ #
    lk = _load_runs(out / "runs" / "leakage")
    if len(lk):
        lk.to_csv(tables / "leakage_runs.csv", index=False)
        t2 = lk.groupby("protocol").agg(
            runs=("seed", "size"),
            test_source_overlap=("test_source_overlap", _mean_sd),
            accuracy=("accuracy", _mean_sd),
            macro_f1=("macro_f1", _mean_sd),
            mcc=("mcc", _mean_sd),
        ).reset_index()
        t2.to_csv(tables / "table2_leakage.csv", index=False)
        md += ["## Table 2. Leakage audit (InceptionV4, image-level vs source-grouped split)", "", _md(t2), ""]
        fig, ax = plt.subplots(figsize=(4.2, 3.4))
        g = lk.groupby("protocol")["macro_f1"]
        order = [p for p in ("random", "grouped") if p in g.groups]
        ax.bar(order, [g.get_group(p).mean() for p in order],
               yerr=[g.get_group(p).std(ddof=1) if len(g.get_group(p)) > 1 else 0 for p in order],
               color=["#c44e52", "#4c72b0"][: len(order)], capsize=4)
        ax.set_ylabel("Test macro-F1")
        ax.set_ylim(0, 1.05)
        ax.set_xticks(range(len(order)), ["image-level\n(random)" if p == "random" else "source-grouped" for p in order])
        fig.tight_layout()
        fig.savefig(figs / "fig_leakage.png", dpi=300)
        plt.close(fig)

    # ---- Table 3-5: benchmark -------------------------------------------- #
    bm = _load_runs(out / "runs" / "benchmark")
    if len(bm):
        bm.to_csv(tables / "benchmark_runs.csv", index=False)
        model_order = [m["name"] for m in cfg["models"] if m["name"] in set(bm["model"])]
        y = df["label"].to_numpy()
        groups = df["group"].to_numpy()
        rows, pc_rows, oof_correct = [], [], {}
        for name in model_order:
            r = bm[bm["model"] == name]
            oof = _pooled_oof(out, name, len(df))
            have = ~np.isnan(oof).any(1)
            pred = oof[have].argmax(1)
            ci = S.cluster_bootstrap_ci(y[have], pred, groups[have], reps=reps)
            pooled = E.classification_metrics(y[have], pred, labels)
            oof_correct[name] = (pred == y[have], have)
            rows.append({
                "model": name, "folds": len(r),
                "accuracy": _mean_sd(r["accuracy"]), "macro_f1": _mean_sd(r["macro_f1"]),
                "mcc": _mean_sd(r["mcc"]), "kappa": _mean_sd(r["kappa"]),
                "ece_raw": _mean_sd(r["ece"]), "ece_temp_scaled": _mean_sd(r["ece_calibrated"]),
                "pooled_acc_95ci": f"{pooled['accuracy']:.4f} [{ci['acc_ci_low']:.4f}, {ci['acc_ci_high']:.4f}]",
                "pooled_f1_95ci": f"{pooled['macro_f1']:.4f} [{ci['f1_ci_low']:.4f}, {ci['f1_ci_high']:.4f}]",
                "params_M": f"{r['params'].iloc[0] / 1e6:.1f}",
                "GFLOPs": f"{r['flops'].iloc[0] / 1e9:.2f}",
                "img_size": int(r["img_size"].iloc[0]),
                "train_min_per_fold": f"{r['train_time_s'].mean() / 60:.1f}",
            })
            pc = {"model": name}
            for lab in labels:
                pc[names[lab]] = f"{pooled.get(f'f1_class{lab}', float('nan')):.4f}"
            pc_rows.append(pc)
            cm = E.confusion(y[have], pred, n_cls)
            pd.DataFrame(cm, index=names, columns=names).to_csv(tables / f"confusion_oof_{name}.csv")
            _plot_confusion(cm, names, f"{name}: pooled out-of-fold", figs / f"fig_confusion_{name}.png")
        t3 = pd.DataFrame(rows)
        t3.to_csv(tables / "table3_benchmark.csv", index=False)
        t4 = pd.DataFrame(pc_rows)
        t4.to_csv(tables / "table4_per_class_f1.csv", index=False)
        md += ["## Table 3. Source-grouped cross-validation (mean ± SD over folds; pooled OOF with 95% cluster-bootstrap CI)",
               "", _md(t3), "", "## Table 4. Per-class F1 (pooled out-of-fold)", "", _md(t4), ""]

        # McNemar vs reference model, Bonferroni-adjusted; Friedman over folds
        ref = cfg["experiments"]["explain"]["model"]
        if ref in oof_correct:
            mc_rows = []
            for name in model_order:
                if name == ref:
                    continue
                a, ha = oof_correct[ref]
                b, hb = oof_correct[name]
                if ha.sum() != hb.sum():
                    continue
                res = S.mcnemar_exact(a, b)
                mc_rows.append({"comparison": f"{ref} vs {name}", **res})
            if mc_rows:
                adj = S.bonferroni([r["p_value"] for r in mc_rows])
                for r, p in zip(mc_rows, adj):
                    r["p_bonferroni"] = p
                t5 = pd.DataFrame(mc_rows)
                t5.to_csv(tables / "table5_mcnemar.csv", index=False)
                md += ["## Table 5. Exact McNemar tests on pooled out-of-fold predictions (Bonferroni-adjusted)", "",
                       _md(t5.assign(p_value=t5.p_value.map("{:.3g}".format), p_bonferroni=t5.p_bonferroni.map("{:.3g}".format))), ""]
        fr = S.friedman({n: bm[bm.model == n].sort_values("fold")["macro_f1"].to_numpy() for n in model_order})
        md += [f"Friedman test across models on per-fold macro-F1: chi2 = {fr['statistic']:.3f}, p = {fr['p_value']:.3g}", ""]

        fig, ax = plt.subplots(figsize=(6.4, 3.4))
        g = bm.groupby("model")["macro_f1"]
        ax.bar(model_order, [g.get_group(n).mean() for n in model_order],
               yerr=[g.get_group(n).std(ddof=1) if len(g.get_group(n)) > 1 else 0 for n in model_order],
               capsize=3, color="#4c72b0")
        ax.set_ylabel("Macro-F1 (source-grouped CV)")
        ax.set_ylim(0, 1.05)
        ax.tick_params(axis="x", rotation=30)
        fig.tight_layout()
        fig.savefig(figs / "fig_benchmark.png", dpi=300)
        plt.close(fig)

        # reliability diagram for the reference model (pooled OOF)
        if ref in model_order:
            oof = _pooled_oof(out, ref, len(df))
            have = ~np.isnan(oof).any(1)
            temps = bm[bm.model == ref].set_index("fold")["temperature"]
            fold_of = pd.read_csv(out / "folds.csv")["fold"].to_numpy()
            cal = np.vstack([E.softmax(oof[i:i + 1], temps.get(fold_of[i], 1.0)) for i in np.flatnonzero(have)])
            _reliability(E.softmax(oof[have]), cal, y[have], figs / f"fig_reliability_{ref}.png")
            hist_p = out / "histories" / f"{ref}_fold0.csv"
            if hist_p.exists():
                h = pd.read_csv(hist_p)
                fig, axes = plt.subplots(1, 2, figsize=(7.6, 3.0))
                axes[0].plot(h.epoch, h.train_loss, label="train")
                axes[0].plot(h.epoch, h.val_loss, label="validation")
                axes[0].set_ylabel("Loss")
                axes[1].plot(h.epoch, h.train_acc, label="train")
                axes[1].plot(h.epoch, h.val_acc, label="validation")
                axes[1].set_ylabel("Accuracy")
                for a in axes:
                    a.set_xlabel("Epoch")
                    a.legend(fontsize=8)
                fig.tight_layout()
                fig.savefig(figs / f"fig_curves_{ref}_fold0.png", dpi=300)
                plt.close(fig)

        # ---- Table 6: external ------------------------------------------- #
        if "ext_full_accuracy" in bm.columns and ext_df is not None:
            ext_y = ext_df["label"].to_numpy()
            shared = sorted(set(ext_y))
            rows = []
            for name in model_order:
                r = bm[bm.model == name]
                rows.append({
                    "model": name,
                    "accuracy_4way": _mean_sd(r["ext_full_accuracy"]),
                    "macro_f1_4way": _mean_sd(r["ext_full_macro_f1"]),
                    "accuracy_shared_only": _mean_sd(r["ext_restricted_accuracy"]),
                    "macro_f1_shared_only": _mean_sd(r["ext_restricted_macro_f1"]),
                    "pred_leaf_smut_frac": _mean_sd(r["ext_frac_pred_outside_shared"]),
                })
                cm = np.zeros((n_cls, n_cls), dtype=int)
                for p in sorted((out / "runs" / "benchmark").glob(f"{name}_fold*.npz")):
                    z = np.load(p)
                    if "ext_logits" in z:
                        cm += E.confusion(ext_y, z["ext_logits"].argmax(1), n_cls)
                pd.DataFrame(cm, index=names, columns=names).to_csv(tables / f"confusion_external_{name}.csv")
                if name == ref:
                    keep = [i for i in range(n_cls) if i in shared]
                    _plot_confusion(cm[keep], names, f"{name}: external (summed over folds)",
                                    figs / f"fig_confusion_external_{name}.png")
            t6 = pd.DataFrame(rows)
            t6.to_csv(tables / "table6_external.csv", index=False)
            md += ["## Table 6. Zero-shot external test (Paddy Doctor shared classes; mean ± SD over fold models)",
                   "", _md(t6), ""]

    # ---- Table 7: deployment --------------------------------------------- #
    xp = tables / "export_metrics.csv"
    if xp.exists():
        t7 = pd.read_csv(xp)
        md += ["## Table 7. Deployment (ONNX Runtime, CPU, batch 1)", "", _md(t7.round(4)), ""]

    (out / "summary.md").write_text("\n".join(md), encoding="utf-8")
    log(f"report: wrote {out / 'summary.md'}")
